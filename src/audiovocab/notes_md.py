"""Render the Phase 1 behaviour tables (reports/phase1_behaviour.json) into MODEL_NOTES.md, below a marker line.
No number is typed by hand."""
import json

from .config import ROOT, path

MARK = "<!-- behaviour tables: generated by audiovocab.notes_md, do not edit below -->"


def _f(x, d=3):
    return f"{x:.{d}f}"


def render():
    d = json.loads((path("reports") / "phase1_behaviour.json").read_text(encoding="utf-8"))
    par = json.loads((path("reports") / "parity.json").read_text(encoding="utf-8"))
    n = d["n_clips"]
    L = ["2", "5", "10", "20", "30", "40", "60"]
    out = [MARK, "", f"### Length (n = {n} clips; cosine to the same clip at 30 s, mean and min)", "",
           "| Length (s) | " + " | ".join(L) + " |", "|---|" + "---|" * len(L)]
    for m in ("gemma", "clap"):
        r = d[m]["length"]
        out.append(f"| {m} | " + " | ".join(f"{_f(r[x]['cos_to_30s']['mean'])} ({_f(r[x]['cos_to_30s']['min'])})" for x in L) + " |")
    out += ["", "| | Gemma | CLAP |", "|---|---|---|"]
    for k, lab in [("next_20s_window_cos", "Next, non-overlapping 20 s window vs this 20 s window (content drift baseline), mean"),
                   ("truncation_40_vs_30_max_abs_diff", "40 s vs 30 s embedding, max abs difference"),
                   ("truncation_60_vs_30_max_abs_diff", "60 s vs 30 s embedding, max abs difference")]:
        g, c = d["gemma"]["length"][k], d["clap"]["length"][k]
        out.append(f"| {lab} | {_f(g['mean'] if isinstance(g, dict) else g)} | {_f(c['mean'] if isinstance(c, dict) else c)} |")
    out += ["", "- **Gemma truncates at 30 s** (difference exactly 0). CLAP keeps changing past 30 s, because our wrapper "
            "averages extra 10 s windows.",
            "- Shorter clips drift away from the 30 s vector, but even a 10 s clip stays closer to it than the next 20 s "
            "of the same show is to this one. **Content moves the vector more than length does.** "
            "Phase 3 therefore uses windows of ≤ 10 s for sounds and 10 s windows for music."]

    out += ["", f"### Loudness (10 s clips, cosine to 0 dB; mean and min)", "", "| Gain | " +
            " | ".join(f"{g} dB" for g in ["-12", "-6", "0", "6"]) + " |", "|---|---|---|---|---|"]
    for m in ("gemma", "clap"):
        r = d[m]["loudness"]
        out.append(f"| {m} | " + " | ".join(f"{_f(r[g]['mean'])} ({_f(r[g]['min'])})" for g in ["-12", "-6", "0", "6"]) + " |")
    out += ["", "- **Gemma is close to loudness-invariant**; CLAP drops more at −12 dB. +6 dB was applied without "
            "clipping protection."]

    out += ["", "### Silence and noise (10 s)", "", "| | Gemma | CLAP |", "|---|---|---|"]
    out.append(f"| Clip↔clip cosine, mean | {_f(d['gemma']['synthetic']['clip_to_clip_cos']['mean'])} | "
               f"{_f(d['clap']['synthetic']['clip_to_clip_cos']['mean'])} |")
    for k in ("silence", "white", "pink"):
        g, c = d["gemma"]["synthetic"][k], d["clap"]["synthetic"][k]
        out.append(f"| {k} ↔ clips, mean cosine | {_f(g['cos_to_clips']['mean'])} | {_f(c['cos_to_clips']['mean'])} |")
        out.append(f"| clips for which {k} is nearer than their nearest real clip (of {n}) | "
                   f"{g['closer_than_nearest_real_neighbour']} | {c['closer_than_nearest_real_neighbour']} |")
    out += ["", "- **Silence is not a hub** in either model: no clip has silence as its nearest neighbour.",
            "- In Gemma **everything is close to everything** (clip↔clip about 0.7, and even silence↔speech about "
            "0.67): the space is a narrow cone. Absolute cosines are therefore not comparable across models; only "
            "rankings and contrasts are. CLAP spreads clips much more widely (silence↔speech ≈ 0)."]

    w = d["gemma"]["wording"]
    out += ["", "### Text wording (Gemma; 8 concepts × word / phrase / description)", "",
            "| Prefix | Same text with vs without prefix | Same concept, different wording | Different concepts, same form | Text↔audio: word | phrase | description |",
            "|---|---|---|---|---|---|---|"]
    for p in ("none", "SearchQuery", "Document", "Classification"):
        r = w[p]
        pv = "—" if p == "none" else _f(w["prefix_vs_none_same_text"][p]["mean"])
        ta = r["text_to_audio_by_form"]
        out.append(f"| {p} | {pv} | {_f(r['same_concept_diff_wording']['mean'])} | {_f(r['diff_concept_same_form']['mean'])} | "
                   f"{_f(ta['word']['mean'])} | {_f(ta['phrase']['mean'])} | {_f(ta['description']['mean'])} |")
    c = d["clap"]["wording"]["none"]
    ta = c["text_to_audio_by_form"]
    out.append(f"| CLAP (no prefixes) | — | {_f(c['same_concept_diff_wording']['mean'])} | {_f(c['diff_concept_same_form']['mean'])} | "
               f"{_f(ta['word']['mean'])} | {_f(ta['phrase']['mean'])} | {_f(ta['description']['mean'])} |")
    out += ["", "- **The prefix is a big move**: the same text with `SearchQuery` has cosine "
            f"{_f(w['prefix_vs_none_same_text']['SearchQuery']['mean'])} with the bare text; `Classification` moves it "
            f"further ({_f(w['prefix_vs_none_same_text']['Classification']['mean'])}). `SearchQuery` and `Document` are "
            f"nearly the same direction ({_f(w['searchquery_vs_document_same_text']['mean'])}).",
            "- **Prefixes push text away from audio** in raw cosine (bare text sits closest). That's a shift of the "
            "whole text cloud (the modality gap), not necessarily worse ranking. Which form ranks clips best is "
            "measured as zero-shot accuracy on a tuning split in Phase 4, and the choice is fixed before the "
            "reported split is scored.",
            "- Wording matters less than concept: same-concept rewordings stay closer than different concepts in the "
            "same form, for every prefix."]

    t = {m: d[m]["timing"] for m in ("gemma", "clap")}
    out += ["", "### Embedding cost (CPU, 12 cores)", "", "| Clip length | 1 s | 2 s | 5 s | 10 s |", "|---|---|---|---|---|"]
    for m in ("gemma", "clap"):
        out.append(f"| {m}: s per clip | " + " | ".join(_f(t[m][k]["s_per_clip"], 2) for k in ("1", "2", "5", "10")) + " |")
    out += ["", f"Measured while downloads were also running, so these are upper bounds. A clean single 20 s clip "
            f"(Phase 0 parity run) took **{par['gemma_s_per_20s_clip']} s with Gemma** and **{par['clap_s_per_20s_clip']} s with "
            "CLAP**. Gemma costs about 10× CLAP. There's a fixed per-clip overhead, so many short clips cost more per "
            "second of audio than a few long ones."]
    return "\n".join(out) + "\n"


def write():
    f = ROOT / "MODEL_NOTES.md"
    txt = f.read_text(encoding="utf-8").split(MARK)[0].rstrip() + "\n\n"
    f.write_text(txt + render(), encoding="utf-8")
